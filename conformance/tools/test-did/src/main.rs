//! Translates `test/*.test.did` into Lean, for the model to check and turn into vectors.
//!
//! ```text
//! cargo run -- ../../../test/*.test.did > ../../../lean/Oracle/TestDid/Data.lean
//! ```
//!
//! Each assertion becomes an `Oracle.TestDid.Assert` (`lean/Oracle/TestDid/Assert.lean`):
//! its message, its types as a type table, and its claim. Nothing is decided here --
//! whether the model agrees with a claim is `lean/Oracle/TestDid.lean`'s question -- with
//! one exception: the model has no textual syntax yet, so text in an assertion is
//! carried with the values `candid_parser` reads it as.
//!
//! This exists while `test/` does. CI runs it and fails if the output differs from the
//! committed file, so the `.test.did` files stay the source of these assertions.

use candid_parser::candid::types::value::{IDLField, IDLValue, VariantValue};
use candid_parser::candid::types::{FuncMode, Type, TypeEnv, TypeInner};
use candid_parser::syntax::IDLProg;
use candid_parser::test::{Assert, Input, Test};
use candid_parser::typing::{ast_to_type, check_prog};
use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;
use std::path::Path;
use std::process::ExitCode;

type Result<T> = std::result::Result<T, String>;

fn main() -> ExitCode {
    let paths: Vec<String> = std::env::args().skip(1).collect();
    if paths.is_empty() {
        eprintln!("usage: conformance-test-did <file.test.did>...");
        return ExitCode::from(2);
    }
    match translate_all(&paths) {
        Ok(lean) => {
            print!("{lean}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("{e}");
            ExitCode::FAILURE
        }
    }
}

fn translate_all(paths: &[String]) -> Result<String> {
    let mut out = String::from(HEADER);
    let mut names = Vec::new();
    for path in paths {
        let file = Path::new(path)
            .file_name()
            .and_then(|f| f.to_str())
            .and_then(|f| f.strip_suffix(".test.did"))
            .ok_or_else(|| format!("{path}: not a .test.did file"))?;
        let source = std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
        let test: Test = source.parse().map_err(|e| format!("{path}: {e}"))?;
        let name = format!("{}Asserts", lower_camel(file));
        out += &translate(file, &name, test).map_err(|e| format!("{path}: {e}"))?;
        names.push(name);
    }
    writeln!(
        out,
        "/-- Every assertion, file by file. -/\ndef asserts : List Assert :=\n  {}\n\nend Oracle.TestDid",
        names.join(" ++ ")
    )
    .unwrap();
    Ok(out)
}

const HEADER: &str = "\
/-
Generated by `conformance/tools/test-did` from `test/*.test.did`. Do not edit: change a
`.test.did` file and run the tool again. See `Oracle/TestDid.lean`.
-/

import Oracle.TestDid.Assert

namespace Oracle.TestDid

open Candid

";

/// `construct` is `construct`, `sub-types` would be `subTypes`.
fn lower_camel(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(if upper { c.to_ascii_uppercase() } else { c });
            upper = false;
        } else {
            upper = true;
        }
    }
    out
}

fn translate(file: &str, name: &str, test: Test) -> Result<String> {
    let mut env = TypeEnv::new();
    let prog = IDLProg {
        decs: test.defs,
        actor: None,
    };
    check_prog(&mut env, &prog).map_err(|e| e.to_string())?;
    let names = unique_names(&test.asserts);
    let mut out = format!("def {name} : List Assert := [\n");
    for (i, (assert, desc)) in test.asserts.iter().zip(names).enumerate() {
        let types = assert
            .typ
            .iter()
            .map(|t| ast_to_type(&env, &t.typ))
            .collect::<std::result::Result<Vec<_>, _>>()
            .map_err(|e| format!("{desc}: {e}"))?;
        let entry =
            assertion(file, &desc, assert, &env, &types).map_err(|e| format!("{desc}: {e}"))?;
        let sep = if i == 0 { "  " } else { "  , " };
        writeln!(out, "{sep}{entry}").unwrap();
    }
    out += "  ]\n\n";
    Ok(out)
}

/// Descriptions, made unique within a file: an empty one, or one that repeats, gets
/// the assertion's number.
fn unique_names(asserts: &[Assert]) -> Vec<String> {
    let mut count: HashMap<String, usize> = HashMap::new();
    for a in asserts {
        *count.entry(a.desc()).or_default() += 1;
    }
    asserts
        .iter()
        .enumerate()
        .map(|(i, a)| {
            let desc = a.desc();
            if desc.is_empty() {
                format!("#{}", i + 1)
            } else if count[&desc] > 1 {
                format!("{desc} #{}", i + 1)
            } else {
                desc
            }
        })
        .collect()
}

fn assertion(
    file: &str,
    name: &str,
    assert: &Assert,
    env: &TypeEnv,
    types: &[Type],
) -> Result<String> {
    let left = input(&assert.left, env, types)?;
    let claim = match (&assert.right, assert.pass) {
        (None, true) => ".decodes".to_string(),
        (None, false) => ".rejects".to_string(),
        (Some(r), true) => format!(".equals ({})", input(r, env, types)?),
        (Some(r), false) => format!(".differs ({})", input(r, env, types)?),
    };
    Ok(format!(
        "{{ file := {}, name := {}, input := {left}, types := {}, claim := {claim} }}",
        lean_string(file),
        lean_string(name),
        TableBuilder::types(env, types)?,
    ))
}

/// Text is read the way `candid_parser`'s own test runner reads it.
fn input(i: &Input, env: &TypeEnv, types: &[Type]) -> Result<String> {
    match i {
        Input::Blob(bytes) => Ok(format!(".blob {}", lean_string(&hex(bytes)))),
        Input::Text(s) => {
            let values = match i.parse(env, types) {
                Ok(args) => {
                    let vs = args.args.iter().map(value).collect::<Result<Vec<_>>>()?;
                    format!("(some [{}])", vs.join(", "))
                }
                Err(_) => "none".to_string(),
            };
            Ok(format!(".text {} {values}", lean_string(s)))
        }
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn byte_list(bytes: &[u8]) -> String {
    let bs: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
    format!("[{}]", bs.join(", "))
}

/// A Lean string literal. Non-ASCII characters are written as themselves, since Lean
/// source is UTF-8; control characters are escaped.
fn lean_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out += "\\\"",
            '\\' => out += "\\\\",
            '\n' => out += "\\n",
            '\t' => out += "\\t",
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                write!(out, "\\x{:02x}", c as u32).unwrap()
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A value as a Lean `Value`. `null`, an absent option and `reserved`'s value are all
/// `.null`, as in the model.
fn value(v: &IDLValue) -> Result<String> {
    Ok(match v {
        IDLValue::Null | IDLValue::None | IDLValue::Reserved => ".null".into(),
        IDLValue::Bool(b) => format!(".bool {b}"),
        IDLValue::Nat(n) => format!(".nat {n}"),
        IDLValue::Int(i) => format!(".int ({i})"),
        IDLValue::Nat8(n) => format!(".nat8 {n}"),
        IDLValue::Nat16(n) => format!(".nat16 {n}"),
        IDLValue::Nat32(n) => format!(".nat32 {n}"),
        IDLValue::Nat64(n) => format!(".nat64 {n}"),
        IDLValue::Int8(i) => format!(".int8 ({i})"),
        IDLValue::Int16(i) => format!(".int16 ({i})"),
        IDLValue::Int32(i) => format!(".int32 ({i})"),
        IDLValue::Int64(i) => format!(".int64 ({i})"),
        IDLValue::Float32(f) => format!(".float32 0x{:08x}", f.to_bits()),
        IDLValue::Float64(f) => format!(".float64 0x{:016x}", f.to_bits()),
        IDLValue::Text(s) => format!(".text {}", lean_string(s)),
        IDLValue::Opt(v) => format!(".opt ({})", value(v)?),
        IDLValue::Vec(vs) => {
            let vs = vs.iter().map(value).collect::<Result<Vec<_>>>()?;
            format!(".vec [{}]", vs.join(", "))
        }
        IDLValue::Blob(bs) => {
            let vs: Vec<String> = bs.iter().map(|b| format!(".nat8 {b}")).collect();
            format!(".vec [{}]", vs.join(", "))
        }
        IDLValue::Record(fs) => {
            let mut sorted: BTreeMap<u32, String> = BTreeMap::new();
            for IDLField { id, val } in fs {
                sorted.insert(id.get_id(), value(val)?);
            }
            let fs: Vec<String> = sorted
                .iter()
                .map(|(id, v)| format!("({id}, {v})"))
                .collect();
            format!(".record [{}]", fs.join(", "))
        }
        IDLValue::Variant(VariantValue(f, _)) => {
            format!(".variant {} ({})", f.id.get_id(), value(&f.val)?)
        }
        IDLValue::Principal(p) => format!(".principal {}", byte_list(p.as_slice())),
        IDLValue::Service(p) => format!(".service {}", byte_list(p.as_slice())),
        IDLValue::Func(p, m) => format!(".func {} {}", byte_list(p.as_slice()), lean_string(m)),
        IDLValue::Number(n) => return Err(format!("a number without a type: {n}")),
    })
}

/// Builds the type table for one assertion's types. Each named type gets one entry,
/// which is what lets a recursive one be written down; an anonymous composite gets an
/// entry where it occurs.
struct TableBuilder<'a> {
    env: &'a TypeEnv,
    entries: Vec<Option<String>>,
    named: HashMap<String, String>,
}

impl<'a> TableBuilder<'a> {
    fn types(env: &'a TypeEnv, types: &[Type]) -> Result<String> {
        let mut b = TableBuilder {
            env,
            entries: Vec::new(),
            named: HashMap::new(),
        };
        let roots = types
            .iter()
            .map(|t| b.slot(t))
            .collect::<Result<Vec<_>>>()?;
        let entries = b
            .entries
            .into_iter()
            .map(|e| e.ok_or("an entry was never filled in".to_string()))
            .collect::<Result<Vec<_>>>()?;
        Ok(format!(
            "⟨{{ entries := #[{}] }}, [{}]⟩",
            entries.join(", "),
            roots.join(", ")
        ))
    }

    fn slot(&mut self, t: &Type) -> Result<String> {
        let prim = match t.as_ref() {
            TypeInner::Null => "null",
            TypeInner::Bool => "bool",
            TypeInner::Nat => "nat",
            TypeInner::Int => "int",
            TypeInner::Nat8 => "nat8",
            TypeInner::Nat16 => "nat16",
            TypeInner::Nat32 => "nat32",
            TypeInner::Nat64 => "nat64",
            TypeInner::Int8 => "int8",
            TypeInner::Int16 => "int16",
            TypeInner::Int32 => "int32",
            TypeInner::Int64 => "int64",
            TypeInner::Float32 => "float32",
            TypeInner::Float64 => "float64",
            TypeInner::Text => "text",
            TypeInner::Reserved => "reserved",
            TypeInner::Empty => "empty",
            TypeInner::Principal => "principal",
            TypeInner::Var(name) => return self.named(name),
            _ => {
                let i = self.reserve();
                let c = self.composite(t)?;
                self.entries[i] = Some(c);
                return Ok(format!(".ref {i}"));
            }
        };
        Ok(format!(".prim .{prim}"))
    }

    /// A named type: its entry, made on first use. A name that stands for a primitive,
    /// or for another name, has no entry of its own.
    fn named(&mut self, name: &str) -> Result<String> {
        if let Some(s) = self.named.get(name) {
            return Ok(s.clone());
        }
        let t = self.env.find_type(name).map_err(|e| e.to_string())?.clone();
        if matches!(t.as_ref(), TypeInner::Var(_)) || is_prim(&t) {
            let s = self.slot(&t)?;
            self.named.insert(name.to_string(), s.clone());
            return Ok(s);
        }
        let i = self.reserve();
        let s = format!(".ref {i}");
        self.named.insert(name.to_string(), s.clone());
        let c = self.composite(&t)?;
        self.entries[i] = Some(c);
        Ok(s)
    }

    fn reserve(&mut self) -> usize {
        self.entries.push(None);
        self.entries.len() - 1
    }

    fn composite(&mut self, t: &Type) -> Result<String> {
        Ok(match t.as_ref() {
            TypeInner::Opt(t) => format!(".opt ({})", self.slot(t)?),
            TypeInner::Vec(t) => format!(".vec ({})", self.slot(t)?),
            TypeInner::Record(fs) | TypeInner::Variant(fs) => {
                let mut sorted = BTreeMap::new();
                for f in fs {
                    sorted.insert(f.id.get_id(), self.slot(&f.ty)?);
                }
                let fs: Vec<String> = sorted
                    .iter()
                    .map(|(id, s)| format!("({id}, {s})"))
                    .collect();
                let kind = if matches!(t.as_ref(), TypeInner::Record(_)) {
                    "record"
                } else {
                    "variant"
                };
                format!(".{kind} [{}]", fs.join(", "))
            }
            TypeInner::Func(f) => {
                let args = f
                    .args
                    .iter()
                    .map(|t| self.slot(t))
                    .collect::<Result<Vec<_>>>()?;
                let rets = f
                    .rets
                    .iter()
                    .map(|t| self.slot(t))
                    .collect::<Result<Vec<_>>>()?;
                let modes: Vec<&str> = f
                    .modes
                    .iter()
                    .map(|m| match m {
                        FuncMode::Query => ".query",
                        FuncMode::Oneway => ".oneway",
                        FuncMode::CompositeQuery => ".compositeQuery",
                    })
                    .collect();
                format!(
                    ".func [{}] [{}] [{}]",
                    args.join(", "),
                    rets.join(", "),
                    modes.join(", ")
                )
            }
            TypeInner::Service(ms) => {
                let ms = ms
                    .iter()
                    .map(|(n, t)| Ok(format!("({}, {})", lean_string(n), self.slot(t)?)))
                    .collect::<Result<Vec<_>>>()?;
                format!(".service [{}]", ms.join(", "))
            }
            other => return Err(format!("no table entry for {other:?}")),
        })
    }
}

fn is_prim(t: &Type) -> bool {
    !matches!(
        t.as_ref(),
        TypeInner::Var(_)
            | TypeInner::Opt(_)
            | TypeInner::Vec(_)
            | TypeInner::Record(_)
            | TypeInner::Variant(_)
            | TypeInner::Func(_)
            | TypeInner::Service(_)
            | TypeInner::Class(..)
            | TypeInner::Knot(_)
            | TypeInner::Unknown
            | TypeInner::Future
    )
}
